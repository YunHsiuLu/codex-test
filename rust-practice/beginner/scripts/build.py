"""Build derived course files. Never overwrite exercises, templates, or reference solutions."""
from pathlib import Path
import json, re, shutil, subprocess

ROOT=Path(__file__).resolve().parents[1]
def rs(text): return json.dumps(text,ensure_ascii=False)
def embedded(path): return f'include_str!({rs("../"+path)})'
def main():
 data=json.loads((ROOT/'curriculum.json').read_text())
 units=data['units'];tasks=data['exercises']
 assert [x['id'] for x in units]==list(range(13)), 'Expected units 0 through 12.'
 assert len({t['id'] for t in tasks})==len(tasks), 'Duplicate exercise IDs.'
 out=['// Generated by scripts/build.py; edit curriculum.json and canonical Markdown.','use crate::runner::course::{Unit,Exercise,Kind,IoCase,Rule,Mutation};','pub static UNITS: &[Unit] = &[']
 combined=['# Rust Beginner Course\n\n十三單元的 Rust 程式設計課程。單元教材與作業分開；提示與解法不混入本合併教材。\n\n[課綱](SYLLABUS.md)｜[操作說明](README.md)｜[全部作業與案例](TEST_CASES.md)\n']
 def links(text,path):
  def repl(m):
   destination=m.group(2)
   if '://' in destination or destination.startswith('#'): return m.group(0)
   base,sep,anchor=destination.partition('#')
   resolved=(ROOT/path).parent.joinpath(base).resolve()
   relative=__import__('os').path.relpath(resolved,ROOT)
   return '['+m.group(1)+']('+relative+(sep+anchor if sep else '')+')'
  return re.sub(r'\[([^\]]+)\]\(([^)]+)\)',repl,text)
 for u in units:
  text=(ROOT/u['path']).read_text()
  out.append(f'Unit{{id:{u["id"]},title:{rs(u["title"])},text:{embedded(u["path"])} }},')
  combined.append(links(text,u['path']))
 out+= ['];','pub static EXERCISES: &[Exercise] = &[']
 case_doc=['# 自動驗收案例與完成條件\n\n來源為 curriculum.json；由 scripts/build.py 重建，不改學生作答。每份實作至少十項具名驗收。函式測試與鍵盤輸入案例的意義不同；測試設計題則驗正確版與九個故障版。\n\n函式題不要求 main 額外完成輸出；整合專案會檢查 stdout、stderr 和退出碼。通過程式驗收不代替設計報告與人工評量。\n\n文字比對統一 CRLF／LF 並忽略末端換行，其他空白依契約；數值題容許絕對 1e-8 加相對 1e-9。\n']
 manifest=['[package]','name = "rust-beginner-course"','version = "0.2.0"','edition = "2024"','publish = false','default-run = "rust-beginner-course"','']
 for t in tasks:
  for path in [t['source'],t['solution'],f'exercises/{t["id"]}.md']:
   assert (ROOT/path).is_file(),path
  case_doc.append(f'## {t["id"]}：{t["title"]}\n\n作答：`{t["source"]}`。題目：[規格](exercises/{t["id"]}.md)。\n')
  kind={'program':'Program','function':'Function','test_design':'TestDesign','project':'Project'}[t['kind']]
  literal='Exercise{'+','.join([f'id:{rs(t["id"])}',f'unit:{t["unit"]}',f'title:{rs(t["title"])}',f'kind:Kind::{kind}',f'source:{rs(t["source"])}',f'solution:{rs(t["solution"])}',f'target:{rs(t["target"])}',f'prompt:{embedded("exercises/"+t["id"]+".md")}',f'hint:{rs(t["hint"])}',f'support:{str(t["support"]).lower()}'])+','
  if t['kind']=='function':
   cases=t['checks'];assert len(cases)>=10,t['id']
   assert len({c['name'] for c in cases})==len(cases),t['id']
   tests=['#[cfg(test)]','mod course_checks {','use super::*;']
   for c in cases:
    assert re.fullmatch('[a-zA-Z_][a-zA-Z_0-9]*',c['name'])
    tests.append(f'#[test]\nfn {c["name"]}() {{ {c["check"]} }}')
   tests.append('}')
   checkpath=f'checks/{t["id"]}.rs';(ROOT/checkpath).write_text('\n'.join(tests)+'\n')
   literal+=f'io:&[],harness:{embedded(checkpath)},subject:"",mutations:&[]'+'},'
   for c in cases:case_doc.append(f'- `{c["name"]}`：`{c["check"]}`')
  elif t['kind']=='test_design':
   assert len(t['mutations'])>=9,t['id']
   mutations=','.join(f'Mutation{{name:{rs(m["name"])},code:{embedded(m["path"])}}}' for m in t['mutations'])
   literal+=f'io:&[],harness:"",subject:{embedded(t["subject"])},mutations:&[{mutations}]'+'},'
   case_doc.append('- 正確版本：必須通過學生測試，且測試數不得為零。')
   for m in t['mutations']:case_doc.append(f'- 故障版本「{m["name"]}」：必須被 assertion／測試失敗抓到，編譯失敗與逾時不計。')
  else:
   cases=t['cases'];assert len(cases)>=10,t['id']
   assert len({c['name'] for c in cases})==len(cases),t['id']
   if t['id']!='1-1':assert len({(c['input'],tuple(c['args'])) for c in cases})==len(cases),f'{t["id"]}: duplicate inputs'
   else:case_doc.append('本題固定輸出，以十項相關性質檢查同一次執行，並非十種不同輸入。')
   literals=[]
   for c in cases:
    rule={'text':'Rule::Text','number':'Rule::Number'}.get(c['rule'])
    if rule is None:rule='Rule::Greeting('+c['rule'].split(':')[1]+')'
    fields=[f'name:{rs(c["name"])}',f'input:{rs(c["input"])}',f'stdout:{rs(c["output"])}',f'stderr:{rs(c["stderr"])}',f'exit:{c["exit"]}',f'args:&[{",".join(rs(x) for x in c["args"])}]',f'rule:{rule}']
    literals.append('IoCase{'+','.join(fields)+'}')
    case_doc.append(f'- **{c["name"]}**：stdin `{rs(c["input"])}`；參數 `{rs(c["args"])}`；stdout `{rs(c["output"])}`；stderr `{rs(c["stderr"])}`；exit `{c["exit"]}`。')
   literal+='io:&['+','.join(literals)+'],harness:"",subject:"",mutations:&[]},'
  out.append(literal);case_doc.append('')
  if t['kind']=='test_design':
   pass  # These are test modules included by the grader, not standalone examples.
  elif t['kind']!='project':
   manifest+=['[[example]]',f'name = "answer{t["id"].replace("-","_")}"',f'path = "{t["solution"]}"','']
  else:
   manifest+=['[[example]]',f'name = "answer{t["id"].replace("-","_")}"',f'path = "{t["solution"]}"','']
 out.append('];')
 (ROOT/'src/catalog.rs').write_text('\n'.join(out)+'\n')
 (ROOT/'COURSE.md').write_text('\n\n---\n\n'.join(combined).rstrip()+'\n')
 (ROOT/'TEST_CASES.md').write_text('\n'.join(case_doc).rstrip()+'\n')
 (ROOT/'Cargo.toml').write_text('\n'.join(manifest))
 if shutil.which('rustfmt'):
  subprocess.run(['rustfmt','--edition','2024',str(ROOT/'src/catalog.rs'),*[str(p) for p in (ROOT/'checks').glob('*.rs')]],check=True)
 print(f'Built {len(units)} units and {len(tasks)} exercises; student sources, templates and solutions preserved.')
if __name__=='__main__':main()
