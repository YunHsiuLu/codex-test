"""Build sublesson registry/catalog from JSON. Never edits student exercises."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
items=json.loads((root/'lessons/sublessons.json').read_text())
quote=lambda value:json.dumps(value,ensure_ascii=False)
s='// Generated by scripts/build_sublessons.py; edit lessons/sublessons.json.\nuse super::{Exercise, Fixture, Kind};\npub static EXERCISES: &[Exercise] = &[\n'
catalog='# Sublesson Test Cases\n\n第四課實作子題每題至少十筆不同參數，驗收只替換 target 副本中的 let 設定，不修改學生檔案；第五課另區分既有實作別名與補充閱讀。輸出中的換行以 \\n 表示；空輸出必須完全沒有字元。所有子題先在 beginner 資料夾操作。\n'
seen=set()
for item in items:
    key=item['id'];assert key not in seen;seen.add(key)
    mode=item.get('mode','variants')
    if mode=='variants': assert len(item['cases'])>=10
    assert len({json.dumps(c['parameters'],sort_keys=True) for c in item['cases']})==len(item['cases'])
    assert len({c['name'] for c in item['cases']})==len(item['cases'])
    paths=[item['lesson']]
    if mode!='reading':paths += [f"solutions/{item['example']}.rs",f"examples/{item['example']}.rs"]
    for path in paths:
        assert (root/path).exists(),path
    kind='Kind::Variants' if mode=='variants' else f'Kind::Main({item["main_lesson"]})' if mode=='main' else 'Kind::Reading'
    solution=f'include_str!("../solutions/{item["example"]}.rs")' if mode!='reading' else '""'
    s+=f'    Exercise {{ id: {quote(key)}, title: {quote(item["title"])}, kind: {kind}, example: {quote(item["example"])}, lesson: include_str!("../{item["lesson"]}"), solution: {solution}, fixtures: &[\n'
    if mode!='variants':
        catalog+=f'\n## {key}：{item["title"]}\n\n'+('沿用主課第五課既有十項驗收，不重複計為另一份實作。\n' if mode=='main' else '補充閱讀，沒有作答檔，也不列入十筆測資要求或驗收通過數。\n')
    else: catalog+=f'\n## {key}：{item["title"]}\n\n| 名稱 | 暫存設定 | 預期 stdout |\n| --- | --- | --- |\n'
    for i,c in enumerate(item['cases']):
        params=', '.join(f'({quote(k)}, {quote(v)})' for k,v in c['parameters'])
        s+=f'        Fixture {{ name: {quote(c["name"])}, parameters: &[{params}], expected: {quote(c["expected"])}, args: &[{quote(str(i))}] }},\n'
        setting='；'.join(f'{k} = {v}' for k,v in c['parameters'])
        catalog+=f'| {c["name"]} | `{setting}` | `{quote(c["expected"])}` |\n'
    s+='    ] },\n'
s+='];\n'
(root/'src/sublessons_data.rs').write_text(s)
(root/'lessons/SUBLESSON_TEST_CASES.md').write_text(catalog)
print(f'Generated {len(items)} sublessons, {sum(len(x["cases"]) for x in items)} distinct datasets; no exercises overwritten.')
